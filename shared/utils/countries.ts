const alpha2ByAlpha3 = new Map(ALPHA2_ALPHA3.split(" ").map(pair => [pair.slice(2).toUpperCase(), pair.slice(0, 2).toUpperCase()]));

export function countryOfAlpha3(code: string): string {
	return alpha2ByAlpha3.get(code.toUpperCase()) ?? "Unknown";
}
