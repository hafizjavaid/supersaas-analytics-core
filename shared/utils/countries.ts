const countryNames = new Intl.DisplayNames(["en"], { type: "region" });

export function countryName(code: string) {
	try {
		return countryNames.of(code) ?? code;
	}
	catch {
		return code;
	}
}

// Two letters match a code only, or "us" would also find Russia and Australia.
export function countryCodesMatching(codes: string[], search: string): string[] {
	const term = search.trim().toLowerCase();
	return codes.filter(code => code.toLowerCase() === term || (term.length > 2 && countryName(code).toLowerCase().includes(term)));
}

